CREATE FUNCTION artistready.list_craft_roles(p_craft text) RETURNS jsonb
LANGUAGE sql STABLE SECURITY DEFINER SET search_path=pg_catalog,artistready AS $$
 SELECT coalesce(jsonb_agg(label ORDER BY sort_order),'[]'::jsonb)
 FROM artistready.craft_roles WHERE craft=p_craft AND is_active
$$;
REVOKE ALL ON artistready.craft_roles FROM PUBLIC,artistready_api;
REVOKE ALL ON FUNCTION artistready.list_craft_roles(text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION artistready.list_craft_roles(text) TO artistready_api;
RESET ROLE;
